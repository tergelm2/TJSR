import pandas as pd
df=pd.read_csv('data/raw/annual_aqi_by_county_2023.zip')
print('Shape',df.shape)
print("\nColumns:")
print(df.columns.tolist())
print("\nMissing Values:")
print(df.isnull().sum())
print("\nDuplicate Rows:")
print(df.duplicated().sum())
print("\nDuplicate Counties:")
print(df.duplicated(subset=["State", "County"]).sum())
print("\nMedian AQI Summary:")
print(df["Median AQI"].describe())
print("\nInvalid Median AQI:")
print((df["Median AQI"] < 0).sum())
print("\nYears:")
print(df["Year"].unique())